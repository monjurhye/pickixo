-- Pickixo — 024_closed_testing.sql
-- Google Play closed-test tracking: who the testers are, which apps are in a
-- closed test, and which installs actually opened the app on which day.
--
-- Play Console does not expose per-tester activity through any API, so the
-- apps report it themselves: on launch each app POSTs a heartbeat to
-- /api/testing/heartbeat with its package name and a random install id it
-- generated once. A heartbeat is counted at most once per install per day
-- (closed_test_activity's primary key), so a chatty app cannot inflate a day.
--
-- An install is linked to a tester either by the email the app sent (when the
-- app has Google sign-in or asks the tester once) or by hand from the panel.
--
-- No secrets live in this schema.
--
-- Safe to re-run: Deploy-Web.ps1 applies every migration in order.
--   C:\Pickixo\pgsql\bin\psql.exe -h 127.0.0.1 -U pickixo_admin -d pickixo `
--     -v ON_ERROR_STOP=1 -f database\schema\024_closed_testing.sql
-- ============================================================================
SET client_encoding = 'UTF8';

BEGIN;

-- The tester pool. One list for every app, the same list that is uploaded to
-- the Play Console email list.
CREATE TABLE IF NOT EXISTS closed_test_testers (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email       text NOT NULL UNIQUE CHECK (email = lower(email)),
    name        text NOT NULL DEFAULT '',
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Apps in (or headed for) a closed test. Heartbeats for a package that is not
-- listed here, or is not enabled, are ignored.
CREATE TABLE IF NOT EXISTS closed_test_apps (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    package          text NOT NULL UNIQUE,
    name             text NOT NULL,
    test_started_on  date,
    required_testers integer NOT NULL DEFAULT 12 CHECK (required_testers BETWEEN 1 AND 500),
    required_days    integer NOT NULL DEFAULT 14 CHECK (required_days BETWEEN 1 AND 90),
    enabled          boolean NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now()
);

-- One row per app install. install_id is generated by the app, so it is only
-- trusted to be unique within one package.
CREATE TABLE IF NOT EXISTS closed_test_installs (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    app_id       uuid NOT NULL REFERENCES closed_test_apps(id) ON DELETE CASCADE,
    install_id   text NOT NULL CHECK (length(install_id) BETWEEN 8 AND 64),
    tester_id    uuid REFERENCES closed_test_testers(id) ON DELETE SET NULL,
    device       text NOT NULL DEFAULT '',
    app_version  text NOT NULL DEFAULT '',
    first_seen   timestamptz NOT NULL DEFAULT now(),
    last_seen    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (app_id, install_id)
);

CREATE INDEX IF NOT EXISTS closed_test_installs_tester_idx
    ON closed_test_installs (tester_id);

-- Days an install was opened, in Asia/Dhaka (the testers' day, not UTC's).
CREATE TABLE IF NOT EXISTS closed_test_activity (
    install_id  uuid NOT NULL REFERENCES closed_test_installs(id) ON DELETE CASCADE,
    day         date NOT NULL,
    opens       integer NOT NULL DEFAULT 1,
    PRIMARY KEY (install_id, day)
);

CREATE INDEX IF NOT EXISTS closed_test_activity_day_idx
    ON closed_test_activity (day);

